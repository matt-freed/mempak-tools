#!/usr/bin/env python3
"""Generate internal/mempak/gamecodes.tsv from the No-Intro N64 DAT.

usage: scripts/gamecodes.py N64.dat > internal/mempak/gamecodes.tsv

The DAT (clrmamepro format, with serials) is libretro-database's copy:
https://raw.githubusercontent.com/libretro/libretro-database/master/metadat/no-intro/Nintendo%20-%20Nintendo%2064.dat

Only retail cartridges are kept: prototypes, demos, kiosk carts, hacks,
LodgeNet, iQue, Virtual Console/GameCube ports, homebrew, modern reissues,
cheat carts and add-ons are dropped. A code shared by several dumps (revisions,
Shindou editions) gets the shortest name.
"""
import re
import sys

NONRETAIL = re.compile(
    r'\((?:[^)]*\b(?:Proto|Beta|Demo|Kiosk|Sample|Pirate|Unl|Aftermarket|Hack|Debug|'
    r'Program|Test|LodgeNet|Virtual Console|GameCube|Switch Online|Zelda Collection|'
    r'Limited Run Games|Piko Interactive|N64brew|Presence of Mind|Summer64|China|'
    r'Manual|Audio|World|Unknown|Add-on)\b[^)]*)\)', re.I)
CHEAT = re.compile(r'^(?:Action Replay|GameShark|GameBooster|Xplorer|Equalizer|Game Buster)', re.I)
# Revision and language tags say nothing about which game it is.
STRIP = re.compile(r'\s*\((?:Rev \w+|v[\d.]+\w*|[A-Z][a-z](?:,[A-Z][a-z])*)\)')


def main(path):
    text = open(path, encoding='utf-8').read()
    m = re.search(r'^\tversion "(.*)"', text, re.M)
    version = m.group(1) if m else 'unknown'
    names = {}
    for block in re.findall(r'^game \((.*?)^\)', text, re.M | re.S):
        name = re.search(r'^\tname "(.*)"', block, re.M).group(1)
        s = re.search(r'^\tserial "(.*)"', block, re.M)
        if not s or NONRETAIL.search(name) or CHEAT.match(name):
            continue
        code = s.group(1)
        if not (len(code) == 4 and code.isascii() and code.isalnum() and code[0] in 'NC'):
            continue
        name = STRIP.sub('', name)
        if code not in names or (len(name), name) < (len(names[code]), names[code]):
            names[code] = name
    out = sys.stdout
    out.write(f'# N64 retail game codes from the No-Intro DAT (libretro-database), version {version}.\n')
    out.write('# Generated by scripts/gamecodes.py; do not edit by hand.\n')
    out.write('# code<TAB>name\n')
    for code in sorted(names):
        out.write(f'{code}\t{names[code]}\n')


if __name__ == '__main__':
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
